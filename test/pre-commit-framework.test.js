// POCP under the pre-commit framework (https://pre-commit.com): .pre-commit-hooks.yaml gives
// pocp's three git hooks as hook ids, `pocp trailer` reads the commit source pre-commit passes
// in its environment, and `pocp doctor` recognises hooks pre-commit installed.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { HOOKS, hooksHealth, PRE_COMMIT_HOOK_IDS } from '../src/init.js';
import { git, pocp, read, sampleRepo, write } from './helpers.js';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');

// The few fields of .pre-commit-hooks.yaml these tests read, without a YAML parser.
function manifest() {
  const text = fs.readFileSync(path.join(ROOT, '.pre-commit-hooks.yaml'), 'utf8');
  return text.split(/^- /m).slice(1).map((block) => Object.fromEntries(
    [...block.matchAll(/^\s*(id|entry|language|language_version|stages|pass_filenames): *(.+)$/gm)].map((m) => [m[1], m[2].trim()]),
  ));
}

test('.pre-commit-hooks.yaml has a hook id for each of pocp git hooks, run with the installed node', () => {
  const hooks = manifest();
  assert.deepEqual(hooks.map((h) => h.id).sort(), Object.values(PRE_COMMIT_HOOK_IDS).sort());
  for (const [stage, id] of Object.entries(PRE_COMMIT_HOOK_IDS)) {
    assert.ok(stage in HOOKS, `${stage} is one of pocp's own hooks`);
    const h = hooks.find((x) => x.id === id);
    assert.equal(h.stages, `[${stage}]`, id);
    assert.match(h.entry, /^pocp (gate|trailer|land)\b/, id);
    assert.equal(h.language, 'node', id);
    assert.equal(h.language_version, 'system', `${id}: no node download`);
  }
  assert.equal(hooks.find((h) => h.id === 'pocp-gate').pass_filenames, 'false');
});

test('pocp trailer: pre-commit passes the source in PRE_COMMIT_COMMIT_MSG_SOURCE; merges and squashes get none', () => {
  const dir = sampleRepo({ deep: false });
  write(dir, 'src/math.js', `${read(dir, 'src/math.js')}// note\n`);
  git(dir, 'add', '-A');
  assert.equal(pocp(dir, ['fix', '--intent', 'note']).code, 0);
  const msg = path.join(dir, 'MSG');
  for (const source of ['merge', 'squash']) {
    fs.writeFileSync(msg, 'subject\n');
    assert.equal(pocp(dir, ['trailer', msg], { env: { PRE_COMMIT_COMMIT_MSG_SOURCE: source } }).code, 0);
    assert.doesNotMatch(fs.readFileSync(msg, 'utf8'), /Proof-Of-Change:/, source);
  }
  fs.writeFileSync(msg, 'subject\n');
  assert.equal(pocp(dir, ['trailer', msg], { env: { PRE_COMMIT_COMMIT_MSG_SOURCE: 'message' } }).code, 0);
  assert.match(fs.readFileSync(msg, 'utf8'), /Proof-Of-Change:/);
});

test('pocp gate run by pre-commit (PRE_COMMIT=1) is logged as a commit attempt', () => {
  const dir = sampleRepo({ deep: false });
  pocp(dir, ['gate'], { env: { PRE_COMMIT: '1' } });
  const log = read(dir, '.proof/runs/gate.jsonl').trim().split('\n').map((l) => JSON.parse(l));
  assert.equal(log.at(-1).source, 'hook');
});

// What `pre-commit install` writes into .git/hooks (abridged).
const preCommitHook = (type) => `#!/usr/bin/env bash\n# File generated by pre-commit: https://pre-commit.com\nARGS=(hook-impl --config=.pre-commit-config.yaml --hook-type=${type})\n`;

function installPreCommit(dir, ids) {
  write(dir, '.pre-commit-config.yaml', `repos:\n  - repo: https://github.com/harriswekselblatt/pocp\n    rev: v1.4.0\n    hooks: [${ids.map((id) => `{ id: ${id} }`).join(', ')}]\n`);
  for (const type of Object.keys(PRE_COMMIT_HOOK_IDS)) {
    const file = path.join(dir, '.git', 'hooks', type);
    fs.writeFileSync(file, preCommitHook(type));
    fs.chmodSync(file, 0o755);
  }
}

test('doctor: hooks installed by pre-commit with all three pocp ids are ok', () => {
  const dir = sampleRepo({ deep: false });
  installPreCommit(dir, Object.values(PRE_COMMIT_HOOK_IDS));
  const h = hooksHealth(dir);
  assert.equal(h.managedBy, 'pre-commit');
  assert.deepEqual(h.problems, []);
  const r = pocp(dir, ['doctor', '--json']);
  const hooks = (r.json?.checks || r.json?.results || []).find((c) => c.id === 'hooks');
  assert.equal(hooks?.status, 'ok', r.stdout);
  assert.match(hooks.what, /pre-commit framework/);
});

test('doctor: a pocp id missing from .pre-commit-config.yaml is named, with the pre-commit fix', () => {
  const dir = sampleRepo({ deep: false });
  installPreCommit(dir, ['pocp-gate', 'pocp-land']);
  const h = hooksHealth(dir);
  assert.ok(h.problems.some((p) => /prepare-commit-msg: .*"pocp-trailer"/.test(p)), h.problems.join('\n'));
  const r = pocp(dir, ['doctor', '--json']);
  const hooks = (r.json?.checks || r.json?.results || []).find((c) => c.id === 'hooks');
  assert.equal(hooks?.status, 'problem', r.stdout);
  assert.match(hooks.fix, /pre-commit install/);
});
